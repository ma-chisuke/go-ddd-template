// 集約ルートの契約。どの型が集約ルートかを、規約コメントではなく型で名指す。

package domain

// AggregateRoot は集約ルートが満たす契約である。
//
// 3 つのメソッドは検査のために追加されたものではなく、集約ルートの定義から必然的に
// 導かれる。集約ルートは整合性の境界であるから楽観的排他制御の版を持ち（Version /
// MarkPersisted）、ドメインイベントの発生源であるからイベントを引き出せる（PullEvents）。
// つまりこの契約は、既に在る事実へ名前を与えているだけで、ドメイン型に新しい責務を
// 課してはいない。
//
// DomainEvent がコンテキスト固有であるため、この契約もコンテキストごとに定義する。
// shared には置かない（値オブジェクトをコンテキストごとに所有するのと同じ理由）。
//
// この契約は 3 つの機械検査の判定根拠でもある。
//
//   - 検査 12  公開シグネチャに、集約ルートでないドメイン型へのポインタを出さない
//   - 検査 13  集約ルートとリポジトリ（application.Repos のアクセサ）が 1 対 1 で対応する
//   - 検査 14  集約ストア実装のファイル名が <集約名>_store.go である
//
// いずれも「集約ルートの集合」を下のコンパイル時表明から grep で得る。表明を書き忘れた
// 集約ルートは検査 13(b) が「Repos にアクセサが無い」ではなく「そもそも集約ルートでない」
// と読むため、表明は必ず集約ルートの宣言と同じファイルに置くこと。
//
// 現在この契約を満たすのは StockItem（stock_item.go）だけである。Reservation は
// StockItem の子エンティティであって集約ルートではない。
type AggregateRoot interface {
	// Version は集約が保持しているバージョン番号を返す。永続化済みは 1 以上、
	// 未永続化は 0。比較（compare-and-set）はリポジトリが担う。
	Version() int

	// MarkPersisted は永続化アダプタが書き込み成功後に呼び出し、集約が保持する
	// バージョンを新しい値へ同期する。
	MarkPersisted(version int)

	// PullEvents は蓄積されたドメインイベントを返し、集約内部のイベントを空にする。
	PullEvents() []DomainEvent
}
